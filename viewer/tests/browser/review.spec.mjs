import {test,expect} from '@playwright/test';

test('native slices, five-marker diagnostics and cached landmark previews',async({page})=>{
  test.setTimeout(120000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('#stage')).toHaveAttribute('data-subject','MNI152');
  await expect(page.locator('#toggle-fiducials')).toBeHidden();
  await page.locator('#subject-select').selectOption('synthetic-five');
  await expect(page.locator('#stage')).toHaveAttribute('data-subject','synthetic-five');
  await expect(page.locator('#review-count')).toContainText('5 active candidates');
  await expect(page.locator('#review-status')).toContainText('Select a candidate',{timeout:30000});
  await expect(page.locator('#eeg-status')).toContainText('Scalp tape arcs',{timeout:15000});
  // The save test is repeatable: reset synthetic draft detections and its Nz anchor.
  await page.locator('#detect-threshold').fill('');await page.locator('#detect-run').click();
  await expect(page.locator('#review-count')).toContainText('0/5 confirmed');
  await page.locator('#landmark-select').selectOption('nasion');
  await page.locator('#landmark-snap').uncheck();
  for(const [axis,value] of [['x','0'],['y','77'],['z','0']])await page.locator('#landmark-'+axis).fill(value);
  await page.getByRole('button',{name:'Apply coordinates',exact:true}).click();
  await expect(page.locator('#eeg-status')).toContainText('Scalp tape arcs',{timeout:15000});
  await page.screenshot({path:'test-results/five-marker-head.png'});
  await page.locator('#tab-mri').click();
  await expect(page.locator('#mri-panel')).toHaveAttribute('data-subject','synthetic-five',{timeout:60000});
  await expect(page.locator('#mri-status')).toContainText('RAS mm:');
  const before=await page.locator('#mri-status').textContent();
  await page.locator('#slice-z').fill('650');await page.locator('#slice-z').dispatchEvent('input');
  await expect(page.locator('#mri-status')).not.toHaveText(before);
  await page.locator('#mri-layout').selectOption('axial');
  await page.locator('#mri-overlays').check();
  await page.locator('#mri-radiological').check();
  await page.locator('#mri-layout').selectOption('multi');
  await page.locator('#landmark-select').selectOption('nasion');
  await expect(page.locator('#mri-status')).toContainText('0.00, 77.00, 0.00');
  const revision=await page.locator('#eeg-status').getAttribute('data-revision');
  await page.locator('#landmark-snap').uncheck();
  await page.locator('#landmark-x').fill('1');
  await page.getByRole('button',{name:'Apply coordinates',exact:true}).click();
  await expect(page.locator('#eeg-status')).toContainText('Scalp tape arcs',{timeout:15000});
  await expect(page.locator('#eeg-status')).not.toHaveAttribute('data-revision',revision);
  await page.locator('#mri-reset').click();
  const signal=await page.locator('#mri-canvas').evaluate(async canvas=>{
    const bitmap=await createImageBitmap(canvas), copy=document.createElement('canvas');
    copy.width=bitmap.width;copy.height=bitmap.height;
    const ctx=copy.getContext('2d');ctx.drawImage(bitmap,0,0);
    // Both halves of the centered sagittal phantom must survive reset/redraw.
    return [.2,.35].map(x=>ctx.getImageData(Math.floor(copy.width*x),Math.floor(copy.height*.75),1,1).data[0]);
  });
  expect(signal.every(value=>value>50)).toBe(true);
  await page.locator('#ui').evaluate(element=>{element.scrollTop=0;});
  await page.screenshot({path:'test-results/mri-review.png'});
  await page.locator('#detect-threshold').fill('10000');await page.locator('#detect-run').click();
  await expect(page.locator('#review-count')).toContainText('0 active candidates');
  await page.locator('#detect-undo').click();
  await expect(page.locator('#review-count')).toContainText('5 active candidates');
  await page.locator('#detect-distance').fill('0');await page.locator('#detect-depth').fill('0');
  await page.locator('#detect-run').click();
  await expect(page.locator('#review-count')).toContainText('0 active candidates');
  await expect(page.locator('#candidate-table')).toContainText('too far from head mask');
  await page.locator('#detect-undo').click();
  await expect(page.locator('#review-count')).toContainText('5 active candidates');
  await page.locator('#candidate-table button').filter({hasText:/^Confirm$/}).first().click();
  await expect(page.locator('#review-count')).toContainText('1/5 confirmed');
  const confirmButtons=page.locator('#candidate-table button').filter({hasText:/^Confirm$/});
  for(let i=0;i<5;i++) await confirmButtons.nth(i).click();
  await expect(page.locator('#review-count')).toContainText('5/5 confirmed');
  await page.locator('#review-save').click();
  await expect(page.locator('#review-status')).toContainText('Saved corrections',{timeout:45000});
  await page.reload();
  await expect(page.locator('#stage')).toHaveAttribute('data-subject','MNI152');
  await page.locator('#subject-select').selectOption('synthetic-five');
  await expect(page.locator('#review-count')).toContainText('5/5 confirmed');
  await page.locator('#tab-mri').click();
  await expect(page.locator('#mri-panel')).toHaveAttribute('data-subject','synthetic-five',{timeout:60000});
  await page.locator('#mri-add').click();
  await expect(page.locator('#review-count')).toContainText('6 active candidates');
  await page.locator('#landmark-select').selectOption('manual-1');
  await page.locator('#mri-place').click();
  await expect(page.locator('#info')).toContainText('manually_confirmed');
  await page.locator('#mri-reset').click();
  await expect(page.locator('#mri-status')).toContainText('RAS mm:');
  await page.locator('#tab-head').click();
  await page.locator('#subject-select').selectOption('MNI152');
  await expect(page.locator('#stage')).toHaveAttribute('data-subject','MNI152');
  await expect(page.locator('#toggle-fiducials')).toBeHidden();
  await expect(page.locator('#review-panel')).toBeHidden();
  expect(errors).toEqual([]);
});
